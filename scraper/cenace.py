URL = os.environ.get(
    "CENACE_URL", "https://www.cenace.gob.ec/info-operativa/InformacionOperativa.htm"
)
TZ = ZoneInfo("America/Guayaquil")
ROOT = Path(__file__).resolve().parent.parent
DATA = Path(os.environ.get("DATA_DIR", ROOT / "data"))

MONTHS = {
    "enero": 1, "febrero": 2, "marzo": 3, "abril": 4, "mayo": 5, "junio": 6,
    "julio": 7, "agosto": 8, "septiembre": 9, "setiembre": 9, "octubre": 10,
    "noviembre": 11, "diciembre": 12,
}

# Curve trace name -> CSV column
CURVE_COLS = {
    "hidraulica": "hidraulica_mw",
    "termica": "termica_mw",
    "renovable": "renovable_mw",
    "importacion": "importacion_mw",
    "exportacion": "exportacion_mw",
    "produccion total": "produccion_total_mw",
    "demanda nacional": "demanda_nacional_mw",
}
CURVE_HEADER = ["date", "time"] + list(CURVE_COLS.values())

# KPI box label -> key
KPI_KEYS = {
    "produccion total": "produccion_total",
    "exportacion": "exportacion",
    "importacion": "importacion",
    "hidraulica": "hidraulica",
    "termica": "termica",
    "r. no convencional": "no_convencional",
    "demanda total": "demanda_total",
    "anterior": "demanda_anterior",
    "demanda cnel": "demanda_cnel",
    "empresas electricas": "demanda_empresas",
}
PROD_KPIS = ["produccion_total", "hidraulica", "termica", "no_convencional", "importacion", "exportacion"]
DEMAND_KPIS = ["demanda_total", "demanda_anterior", "demanda_cnel", "demanda_empresas"]


# --------------------------------------------------------------------------- helpers

def norm(text: str) -> str:
    """Lowercase, strip accents and collapse whitespace."""
    text = unicodedata.normalize("NFKD", text or "")
    text = "".join(c for c in text if not unicodedata.combining(c))
    return re.sub(r"\s+", " ", text).strip().lower()


def to_number(text: str) -> float | None:
    """'1 555 534' (nbsp/thin-space thousands separators) -> 1555534.0"""
    if text is None:
        return None
    t = re.sub(r"[\s   ]", "", str(text))
    t = re.sub(r"[^0-9.,\-]", "", t)
    if not t:
        return None
    if "," in t and "." not in t:
        t = t.replace(",", ".")
    else:
        t = t.replace(",", "")
    try:
        return float(t)
    except ValueError:
        return None


def parse_es_date(text: str) -> str | None:
    """'Domingo, 18 de octubre de 2026' -> '2026-10-18'"""
    m = re.search(r"(\d{1,2})\s+de\s+([a-záéíóú]+)\s+de\s+(\d{4})", norm(text))
    if not m or m.group(2) not in MONTHS:
        return None
    return f"{int(m.group(3)):04d}-{MONTHS[m.group(2)]:02d}-{int(m.group(1)):02d}"


_BDATA_FMT = {"f8": "d", "f4": "f", "i1": "b", "u1": "B", "i2": "h", "u2": "H",
              "i4": "i", "u4": "I", "i8": "q", "u8": "Q"}


def decode_array(value):
    """Plotly arrays are either plain lists or {"dtype": "f8", "bdata": "<base64>"}."""
    if isinstance(value, dict) and "bdata" in value:
        fmt = _BDATA_FMT.get(value.get("dtype", "f8"), "d")
        raw = base64.b64decode(value["bdata"])
        n = len(raw) // struct.calcsize(fmt)
        out = list(struct.unpack("<" + fmt * n, raw[: n * struct.calcsize(fmt)]))
        return [None if isinstance(v, float) and v != v else v for v in out]  # NaN -> None
    if isinstance(value, (list, tuple)):
        return [None if isinstance(v, float) and v != v else v for v in value]
    return value


def extract_figures(container) -> list[list[dict]]:
    """Return the trace list of every Plotly.newPlot(...) call inside a container."""
    figures = []
    decoder = json.JSONDecoder()
    for script in container.find_all("script"):
        text = script.string or script.get_text() or ""
        for m in re.finditer(r"Plotly\.newPlot\(\s*\"[^\"]+\"\s*,\s*", text):
            try:
                traces, _ = decoder.raw_decode(text, m.end())
            except json.JSONDecodeError:
                continue
            for tr in traces:
                for key in ("x", "y", "values", "customdata"):
                    if key in tr:
                        tr[key] = decode_array(tr[key])
            figures.append(traces)
    return figures


def r1(v):
    return None if v is None else round(float(v), 3)


# --------------------------------------------------------------------------- parsing

def classify_tab(heading: str) -> str | None:
    h = norm(heading)
    if "tiempo real" in h:
        return "realtime"
    if "demanda" in h:
        return "demand"
    if "diaria" in h:
        return "daily"
    if "mensual" in h:
        return "monthly"
    if "anual" in h:
        return "annual"
    return None


def parse_tab(tab) -> dict:
    out: dict = {}
    span = tab.find("span")
    out["date_text"] = span.get_text(" ", strip=True) if span else None
    out["date"] = parse_es_date(out["date_text"] or "")

    unit_h3 = tab.find("h3")
    out["unit"] = None
    if unit_h3:
        m = re.search(r"\((\w+)\)", unit_h3.get_text())
        out["unit"] = m.group(1) if m else None

    # KPI boxes
    kpis = {}
    for box in tab.select(".resumen-box"):
        divs = box.find_all("div", recursive=False)
        if len(divs) >= 2:
            key = KPI_KEYS.get(norm(divs[0].get_text()), norm(divs[0].get_text()).replace(" ", "_"))
            kpis[key] = to_number(divs[1].get_text())
    out["kpis"] = kpis

    # Plotly figures, identified by content (robust to re-ordering)
    out["plants"] = {}
    out["other_generation"] = {}
    out["curve"] = None
    out["companies"] = {}
    for traces in extract_figures(tab):
        names = [norm(t.get("name", "")) for t in traces]
        types = [t.get("type") for t in traces]
        if "demanda nacional" in names and "scatter" in types:
            times = traces[0].get("x") or []
            series = {}
            for t in traces:
                col = CURVE_COLS.get(norm(t.get("name", "")))
                if col:
                    series[col] = [r1(v) for v in (t.get("y") or [])]
            out["curve"] = {"times": list(times), "series": series}
        elif types and all(tp == "bar" for tp in types) and all(len(t.get("y") or []) == 1 for t in traces):
            target = "other_generation" if "gas natural" in names or "termica" in names else "plants"
            for t in traces:
                out[target][(t.get("name") or "").strip()] = r1((t.get("y") or [None])[0])
        elif types == ["bar"] and traces[0].get("orientation") == "h":
            t = traces[0]
            for name, val in zip(t.get("y") or [], t.get("x") or []):
                out["companies"][str(name).strip()] = r1(val)

    # Fallback for companies: SVG map tooltips "EMELNORTE\n121 MW"
    if not out["companies"]:
        for title in tab.select("svg title"):
            parts = title.get_text("\n").rsplit("\n", 1)
            if len(parts) == 2:
                out["companies"][parts[0].strip()] = to_number(parts[1])

    note = tab.find("p")
    out["note"] = note.get_text(" ", strip=True) if note else None
    return out


def parse_page(html: str) -> dict:
    soup = BeautifulSoup(html, "html.parser")
    tabs = {}
    for tab in soup.select(".tab-content"):
        h2 = tab.find("h2")
        kind = classify_tab(h2.get_text() if h2 else "")
        if kind and kind not in tabs:
            tabs[kind] = parse_tab(tab)
    if "realtime" not in tabs:
        raise ValueError("Could not find the 'PRODUCCIÓN EN TIEMPO REAL' section — page layout may have changed.")
    return tabs


# --------------------------------------------------------------------------- storage

def read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def write_csv(path: Path, header: list[str], rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    with tmp.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=header, extrasaction="ignore")
        w.writeheader()
        for row in rows:
            w.writerow({k: ("" if row.get(k) is None else row.get(k)) for k in header})
    tmp.replace(path)


def upsert(path: Path, header: list[str], keys: list[str], new_rows: list[dict]) -> None:
    rows = read_csv(path)
    # keep any columns that already exist in the file
    for col in (rows[0].keys() if rows else []):
        if col not in header:
            header.append(col)
    index = {tuple(r.get(k, "") for k in keys): i for i, r in enumerate(rows)}
    for nr in new_rows:
        k = tuple("" if nr.get(c) is None else str(nr.get(c)) for c in keys)
        if k in index:
            rows[index[k]].update({c: v for c, v in nr.items() if v is not None})
        else:
            index[k] = len(rows)
            rows.append(nr)
    rows.sort(key=lambda r: tuple(str(r.get(k, "")) for k in keys))
    write_csv(path, header, rows)


def append(path: Path, header: list[str], new_rows: list[dict]) -> None:
    rows = read_csv(path)
    for col in (rows[0].keys() if rows else []):
        if col not in header:
            header.append(col)
    write_csv(path, header, rows + new_rows)


def curve_rows(date: str, curve: dict | None) -> list[dict]:
    if not date or not curve:
        return []
    rows = []
    for i, t in enumerate(curve["times"]):
        row = {"date": date, "time": t}
        has_value = False
        for col, vals in curve["series"].items():
            v = vals[i] if i < len(vals) else None
            row[col] = v
            has_value |= v is not None
        if has_value:  # future half-hours are NaN -> skip
            rows.append(row)
    return rows


def save(tabs: dict, scraped_utc: datetime, last_modified: str | None) -> dict:
    local = scraped_utc.astimezone(TZ)
    stamp = {
        "scraped_at_utc": scraped_utc.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "scraped_at_local": local.strftime("%Y-%m-%d %H:%M"),
        "page_last_modified": last_modified,
    }
    rt, dm = tabs.get("realtime", {}), tabs.get("demand", {})
    dy = tabs.get("daily", {})

    # 1. Half-hourly curves
    upsert(DATA / "curve_realtime.csv", list(CURVE_HEADER), ["date", "time"], curve_rows(rt.get("date"), rt.get("curve")))
    if dy:
        upsert(DATA / "curve_daily.csv", list(CURVE_HEADER), ["date", "time"], curve_rows(dy.get("date"), dy.get("curve")))

    # 2. One snapshot row per run
    last_point = {}
    if rt.get("curve"):
        c = rt["curve"]
        for i in range(len(c["times"]) - 1, -1, -1):
            if any((vals[i] if i < len(vals) else None) is not None for vals in c["series"].values()):
                last_point = {"curve_last_time": c["times"][i],
                              **{f"last_{k}": c["series"][k][i] for k in c["series"]}}
                break
    snap = {**stamp, "realtime_date": rt.get("date"), "demand_date": dm.get("date")}
    snap.update({f"{k}_mwh": rt.get("kpis", {}).get(k) for k in PROD_KPIS})
    snap.update({f"{k}_mw": dm.get("kpis", {}).get(k) for k in DEMAND_KPIS})
    snap.update(last_point)
    snap_header = (["scraped_at_utc", "scraped_at_local", "page_last_modified", "realtime_date", "demand_date"]
                   + [f"{k}_mwh" for k in PROD_KPIS] + [f"{k}_mw" for k in DEMAND_KPIS]
                   + ["curve_last_time"] + [f"last_{c}" for c in CURVE_COLS.values()])
    prev = read_csv(DATA / "snapshots.csv")
    same_page = bool(last_modified) and bool(prev) and prev[-1].get("page_last_modified") == last_modified
    if same_page:
        print(f"Page not updated since last run ({last_modified}); snapshot not duplicated.")
    else:
        append(DATA / "snapshots.csv", snap_header, [snap])

    # 3. Demand per distribution company
    if dm.get("companies") and not same_page:
        append(DATA / "demand_by_company.csv",
               ["scraped_at_utc", "scraped_at_local", "date", "company", "mw"],
               [{**{k: stamp[k] for k in ("scraped_at_utc", "scraped_at_local")},
                 "date": dm.get("date"), "company": n, "mw": v} for n, v in dm["companies"].items()])

    # 4. Plants
    def plant_rows(tab, src):
        rows = []
        for group, items in (("hidro", tab.get("plants", {})), ("otra", tab.get("other_generation", {}))):
            for n, v in items.items():
                rows.append({"date": tab.get("date"), "plant": n, "group": group, "mwh": v,
                             **({"updated_at_local": stamp["scraped_at_local"]} if src == "rt" else {})})
        return rows
    if rt.get("date"):
        upsert(DATA / "plants_realtime.csv", ["date", "plant", "group", "mwh", "updated_at_local"],
               ["date", "plant"], plant_rows(rt, "rt"))
    if dy.get("date"):
        upsert(DATA / "plants_daily.csv", ["date", "plant", "group", "mwh"], ["date", "plant"], plant_rows(dy, "dy"))

    # 5. Validated daily KPIs
    if dy.get("date"):
        row = {"date": dy["date"], "unit": dy.get("unit")}
        row.update({f"{k}": dy.get("kpis", {}).get(k) for k in PROD_KPIS})
        upsert(DATA / "daily_summary.csv", ["date", "unit"] + PROD_KPIS, ["date"], [row])

    # 6. Month-to-date / year-to-date
    prow = []
    for kind in ("monthly", "annual"):
        t = tabs.get(kind)
        if not t:
            continue
        txt = t.get("date_text") or ""
        year = re.search(r"(\d{4})", txt)
        if kind == "monthly":
            mon = next((MONTHS[w] for w in norm(txt).split() if w in MONTHS), None)
            period = f"{year.group(1)}-{mon:02d}" if year and mon else txt
        else:
            period = year.group(1) if year else txt
        r = {"period_type": kind, "period": period, "as_of_text": txt, "unit": t.get("unit"),
             "updated_at_local": stamp["scraped_at_local"]}
        r.update({k: t.get("kpis", {}).get(k) for k in PROD_KPIS})
        prow.append(r)
        # production per plant, month-to-date / year-to-date
        upsert(DATA / "plants_period.csv",
               ["period_type", "period", "plant", "group", "value", "unit", "as_of_text", "updated_at_local"],
               ["period_type", "period", "plant"],
               [{"period_type": kind, "period": period, "plant": n, "group": g, "value": v, "unit": t.get("unit"),
                 "as_of_text": txt, "updated_at_local": stamp["scraped_at_local"]}
                for g, items in (("hidro", t.get("plants", {})), ("otra", t.get("other_generation", {})))
                for n, v in items.items()])
    if prow:
        upsert(DATA / "period_summary.csv",
               ["period_type", "period", "as_of_text", "unit"] + PROD_KPIS + ["updated_at_local"],
               ["period_type", "period"], prow)

    # Daily production per plant, one clean series: CENACE's validated value when published
    # (daily tab, ~2 days later), otherwise the end-of-day real-time value (last capture of that day)
    build_plants_daily_best()

    # 7. Full capture history (every value CENACE showed, kept forever)
    if not same_page:
        n = log_history(tabs, stamp)
        print(f"History: {n} new/changed values logged.")

    latest = {**stamp, "source": URL, "tabs": tabs}
    (DATA / "latest.json").write_text(json.dumps(latest, ensure_ascii=False, indent=1), encoding="utf-8")
    return latest


def build_plants_daily_best() -> None:
    validated = read_csv(DATA / "plants_daily.csv")
    realtime = read_csv(DATA / "plants_realtime.csv")
    vdates = {r["date"] for r in validated}
    rows = [{**r, "source": "validado"} for r in validated]
    rows += [{"date": r["date"], "plant": r["plant"], "group": r["group"], "mwh": r["mwh"],
              "source": "tiempo_real"} for r in realtime if r["date"] not in vdates]
    rows.sort(key=lambda r: (r["date"], r["group"], r["plant"]))
    write_csv(DATA / "plants_daily_best.csv", ["date", "plant", "group", "mwh", "source"], rows)

    # Wide version for Excel: one row per day, one column per plant
    plants = []
    for grp in ("hidro", "otra"):
        tot = {}
        for r in rows:
            if r["group"] == grp:
                tot[r["plant"]] = tot.get(r["plant"], 0) + (to_number(r["mwh"]) or 0)
        plants += sorted(tot, key=lambda p: -tot[p])
    by_date: dict = {}
    for r in rows:
        d = by_date.setdefault(r["date"], {"date": r["date"], "source": r["source"]})
        d[r["plant"]] = r["mwh"]
    write_csv(DATA / "plants_daily_wide.csv", ["date"] + plants + ["source"],
              [by_date[d] for d in sorted(by_date)])


# --------------------------------------------------------------------------- capture history
#
# data/history/YYYY/YYYY-MM-DD.csv  (append-only, one file per capture day, local time)
# Long format: one row per value. A value is written when it is new or differs from the
# last value logged for the same (dataset, date, key, variable) — so intra-day revisions
# made by CENACE are preserved, without repeating unchanged numbers every 30 minutes.
# Instantaneous series (demand per company, demand KPIs) are logged at every capture.

HISTORY = DATA / "history"
HISTORY_HEADER = ["captured_at_utc", "captured_at_local", "page_last_modified",
                  "dataset", "date", "key", "variable", "value"]
ALWAYS_LOG = {"company_demand", "kpi_demand"}


def flatten(tabs: dict) -> list[tuple]:
    """All parsed values as (dataset, date, key, variable, value)."""
    out = []
    for kind, t in tabs.items():
        if kind in ("monthly", "annual"):
            txt = t.get("date_text") or ""
            year = re.search(r"(\d{4})", txt)
            mon = next((MONTHS[w] for w in norm(txt).split() if w in MONTHS), None)
            date = (f"{year.group(1)}-{mon:02d}" if kind == "monthly" and year and mon
                    else (year.group(1) if year else txt))
        else:
            date = t.get("date") or ""
        kpi_ds = "kpi_demand" if kind == "demand" else f"kpi_{kind}"
        for k, v in (t.get("kpis") or {}).items():
            out.append((kpi_ds, date, "", k, v))
        for name, v in (t.get("plants") or {}).items():
            out.append((f"plant_{kind}", date, name, "mwh_hidro", v))
        for name, v in (t.get("other_generation") or {}).items():
            out.append((f"plant_{kind}", date, name, "mwh_otra", v))
        for name, v in (t.get("companies") or {}).items():
            out.append(("company_demand", date, name, "mw", v))
        c = t.get("curve")
        if c:
            ds = {"realtime": "curve_realtime", "daily": "curve_daily"}.get(kind, f"curve_{kind}_maxday")
            for i, tm in enumerate(c["times"]):
                for col, vals in c["series"].items():
                    v = vals[i] if i < len(vals) else None
                    if v is not None:
                        out.append((ds, date, tm, col, v))
        for meta in ("date_text", "unit", "note"):
            if t.get(meta):
                out.append((f"meta_{kind}", date, "", meta, t[meta]))
    return out


def log_history(tabs: dict, stamp: dict) -> int:
    state_file = HISTORY / "last_values.json"
    state = json.loads(state_file.read_text(encoding="utf-8")) if state_file.exists() else {}
    rows = []
    for ds, date, key, var, val in flatten(tabs):
        if val is None:
            continue
        sk = f"{ds}|{date}|{key}|{var}"
        sval = str(val)
        if ds in ALWAYS_LOG or state.get(sk) != sval:
            rows.append({**{k: stamp[k] for k in ("scraped_at_utc", "scraped_at_local", "page_last_modified")},
                         "dataset": ds, "date": date, "key": key, "variable": var, "value": val})
            state[sk] = sval
    if rows:
        day = stamp["scraped_at_local"][:10]
        path = HISTORY / day[:4] / f"{day}.csv"
        path.parent.mkdir(parents=True, exist_ok=True)
        new_file = not path.exists()
        with path.open("a", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            if new_file:
                w.writerow(HISTORY_HEADER)
            for r in rows:
                w.writerow([r["scraped_at_utc"], r["scraped_at_local"], r["page_last_modified"] or "",
                            r["dataset"], r["date"], r["key"], r["variable"], r["value"]])
    # keep the state file small: forget daily keys older than ~10 days (they no longer change)
    cutoff = (datetime.now(TZ).date().toordinal() - 10)
    def keep(k):
        d = k.split("|")[1]
        return not re.fullmatch(r"\d{4}-\d{2}-\d{2}", d) or datetime.strptime(d, "%Y-%m-%d").date().toordinal() >= cutoff
    state = {k: v for k, v in state.items() if keep(k)}
    HISTORY.mkdir(parents=True, exist_ok=True)
    state_file.write_text(json.dumps(state, ensure_ascii=False, sort_keys=True, indent=0), encoding="utf-8")
    return len(rows)


# --------------------------------------------------------------------------- main

def fetch(url: str, attempts: int = 4) -> requests.Response:
    headers = {
        "User-Agent": "Mozilla/5.0 (compatible; cenace-monitor/1.0; +https://github.com)",
        "Cache-Control": "no-cache",
    }
    last = None
    for i in range(attempts):
        try:
            r = requests.get(url, headers=headers, timeout=60)
            r.raise_for_status()
            r.encoding = r.encoding or "utf-8"
            if "Plotly.newPlot" not in r.text:
                raise ValueError("Response does not look like the CENACE page (no Plotly charts).")
            return r
        except Exception as e:  # noqa: BLE001
            last = e
            print(f"attempt {i + 1}/{attempts} failed: {e}", file=sys.stderr)
            time.sleep(10 * (i + 1))
    raise RuntimeError(f"Could not download {url}: {last}")


def main() -> int:
    DATA.mkdir(parents=True, exist_ok=True)
    if len(sys.argv) > 1:  # local testing: python scraper/cenace.py page.html
        html, last_mod = Path(sys.argv[1]).read_text(encoding="utf-8"), None
    else:
        resp = fetch(URL)
        html, last_mod = resp.text, resp.headers.get("Last-Modified")
    work = ROOT / "_work"  # raw page kept for the daily archive (uploaded to GitHub Releases)
    work.mkdir(exist_ok=True)
    (work / "page.html").write_text(html, encoding="utf-8")
    try:
        tabs = parse_page(html)
    except Exception:
        (ROOT / "debug_page.html").write_text(html, encoding="utf-8")  # uploaded as artifact on failure
        raise
    latest = save(tabs, datetime.now(timezone.utc), last_mod)
    rt = latest["tabs"]["realtime"]
    print(f"OK {latest['scraped_at_local']} | realtime date {rt.get('date')} | "
          f"producción {rt['kpis'].get('produccion_total')} MWh | "
          f"curve points {len(curve_rows(rt.get('date'), rt.get('curve')))} | "
          f"demanda {latest['tabs'].get('demand', {}).get('kpis', {}).get('demanda_total')} MW")
    return 0


if __name__ == "__main__":
    sys.exit(main())
