"""
CENACE "Información Operativa" scraper.

Downloads https://www.cenace.gob.ec/info-operativa/InformacionOperativa.htm,
extracts the numbers behind every chart/KPI and stores them as CSV files in
data/. Designed to run every 30 minutes in GitHub Actions.

The page is a static HTML file regenerated by CENACE every ~30 min. Its charts
are Plotly figures whose data is embedded as JSON inside <script> tags
(numeric arrays are sometimes base64-encoded "bdata"), so no browser is needed.

Files written (all UTF-8 CSV, local time = America/Guayaquil):
  data/curve_realtime.csv      half-hourly MW by source, today (preliminary SCADA)   upsert (date, time)
  data/curve_daily.csv         half-hourly MW by source, last validated day          upsert (date, time)
  data/snapshots.csv           one row per run: production KPIs (MWh) + demand KPIs   append
  data/demand_by_company.csv   MW per distribution company, every run                append
  data/plants_realtime.csv     day-to-date MWh per plant (last value of day ~ total) upsert (date, plant)
  data/plants_daily.csv        validated MWh per plant per day                       upsert (date, plant)
  data/plants_daily_best.csv   daily MWh per plant: validated, else end-of-day real-time  rebuilt
  data/plants_daily_wide.csv   same, one column per plant (for Excel)                rebuilt
  data/plants_period.csv       month-to-date (MWh) / year-to-date (GWh) per plant    upsert (period_type, period, plant)
  data/daily_summary.csv       validated daily production KPIs                       upsert (date)
  data/period_summary.csv      month-to-date and year-to-date KPIs                   upsert (period_type, period)
  data/latest.json             everything parsed in the latest run (used by the dashboard)
"""

